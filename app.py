# -----------------------------------------------------------------------------
# 4. Session State 初始化（确保所有状态键完备）
# -----------------------------------------------------------------------------
if "current_role" not in st.session_state:
    st.session_state.current_role = "经纪人"
if "current_member" not in st.session_state:
    st.session_state.current_member = "丈君"
if "story_stage" not in st.session_state:
    st.session_state.story_stage = 1
if "scores" not in st.session_state:
    st.session_state.scores = {"heart": 0, "trust": 0}
if "last_feedback" not in st.session_state:
    st.session_state.last_feedback = ""

# -----------------------------------------------------------------------------
# 5. 侧边栏控制台
# -----------------------------------------------------------------------------
st.sidebar.title("💖 心动控制台")

selected_role = st.sidebar.selectbox("选择互动身份", ROLES, index=ROLES.index(st.session_state.current_role))
if selected_role != st.session_state.current_role:
    st.session_state.current_role = selected_role
    st.session_state.story_stage = 1
    st.session_state.scores = {"heart": 0, "trust": 0}
    st.session_state.last_feedback = ""

selected_member = st.sidebar.selectbox("选择心动成员", list(MEMBERS.keys()), index=list(MEMBERS.keys()).index(st.session_state.current_member))
if selected_member != st.session_state.current_member:
    st.session_state.current_member = selected_member
    st.session_state.story_stage = 1
    st.session_state.scores = {"heart": 0, "trust": 0}
    st.session_state.last_feedback = ""

member_info = MEMBERS[st.session_state.current_member]

st.sidebar.divider()
st.sidebar.markdown(f"### 当前成员：{st.session_state.current_member}")
st.sidebar.write(f"**标签**：{member_info['trait']}")
safe_image(member_info["img"])

st.sidebar.divider()
st.sidebar.markdown(f"❤️ **心动值**：`{st.session_state.scores['heart']}` | 🤝 **信任度**：`{st.session_state.scores['trust']}`")
st.sidebar.markdown(f"📖 **当前剧情**：第 `{st.session_state.story_stage}` 幕")

if st.sidebar.button("🔄 重置当前进度"):
    st.session_state.story_stage = 1
    st.session_state.scores = {"heart": 0, "trust": 0}
    st.session_state.last_feedback = ""
    st.rerun()

# -----------------------------------------------------------------------------
# 6. 主界面渲染与多幕剧情推进循环
# -----------------------------------------------------------------------------
st.title("💖 浪花男子心动日常")
st.caption(f"当前身份：**{st.session_state.current_role}** | 互动对象：**{st.session_state.current_member}**（{member_info['trait']}）")

st.divider()

if st.session_state.last_feedback:
    st.info(st.session_state.last_feedback)

# 安全获取当前【身份】和【成员】对应的独立剧本（如果找不到则降级到经纪人的丈君线）
role_scripts = CHARACTER_SCRIPTS.get(st.session_state.current_role, CHARACTER_SCRIPTS["经纪人"])
member_scripts = role_scripts.get(st.session_state.current_member, CHARACTER_SCRIPTS["经纪人"]["丈君"])

stage = st.session_state.story_stage

# 第一幕与第二幕渲染逻辑
if stage in [1, 2]:
    s_data = member_scripts[stage]
    st.subheader(s_data["title"])
    st.write(s_data["desc"])

    col1, col2 = st.columns(2)
    with col1:
        if st.button(f"A. {s_data['opt_A']}"):
            st.session_state.scores["heart"] += random.randint(1, 2)
            st.session_state.last_feedback = f"反馈：{s_data['res_A']}"
            st.session_state.story_stage += 1
            st.rerun()

    with col2:
        if st.button(f"B. {s_data['opt_B']}"):
            st.session_state.scores["trust"] += random.randint(1, 2)
            st.session_state.last_feedback = f"反馈：{s_data['res_B']}"
            st.session_state.story_stage += 1
            st.rerun()

# 第三幕：结局结算逻辑
elif stage >= 3:
    st.subheader("📖 本日结局收录")

    heart = st.session_state.scores["heart"]
    trust = st.session_state.scores["trust"]

    if heart >= trust:
        st.success(f"🏆 【{st.session_state.current_member} · 心动大结局】在“{st.session_state.current_role}”身份下，你们之间的心跳频率完全同步，视线再也无法从彼此身上移开！✨")
    else:
        st.warning(f"🥈 【{st.session_state.current_member} · 信任大结局】在“{st.session_state.current_role}”身份下，历经点点滴滴，彼此深厚的信赖感已经化为最长情的告白！💕")

    st.write(f"（隐藏数值结算 — 心动值：{heart} | 信任度：{trust}）")

    if st.button("🔄 开启新的一天 / 重新开始"):
        st.session_state.story_stage = 1
        st.session_state.scores = {"heart": 0, "trust": 0}
        st.session_state.last_feedback = ""
        st.rerun()
